"""Executor 原语：内核只认的稳定引用，不透明。

Task 创建时绑定一根引用；引用保持稳定，**引用指向的定义可以编辑**（ADR-035）。

## 它没有存储，也没有 Port

内核只存那根字符串（`Task.executor_ref`），从不解析它——
"这个引用指向什么、现在能不能用"是网关的事（`gateway/directory/executors.py`）。
所以这个原语在内核里没有需要存的东西，也没有需要外界提供的东西。

这也是"执行者定义不属于内核"的落点：模型、prompt、worker 入口、可调参数全在
`extensions/` 下的声明里，由 `extensions/executors.py` 造出来，登记在网关的四个列表中。

## 它没有命令

`SetSubjectState`（后来差点收成 `SetExecutorState`）**整个删掉**。理由有两条，各自
成立：

**一、它没有调用者。** 全仓搜过：只有 `core/service.py` 定义它、测试调用它，**生产代码
里一个调用者都没有**。

**二、它把一个观测写进了事件链。** `SUBJECT_ONLINE` 说的是"它现在是活的"——ADR-028
明令不落观测，而事件链是**不可删**的，写进去比落表还重。

**根子在于执行者不是那种东西。** 它是**按需起的子进程**：跑完就结束，不"离线"。
"它现在能不能用"是网关算的，而且已经有答案——**三态**（可解析 / 已下线 / 未知，
见 `web/references.py`）。内核没有理由再存一份，而且是更差的一份。

（更早那版叫 `SetSubjectState`，subject 不透明，是**为设备留的**。设备现在是扩展包，
"活着"就是连得上——那是客户端的 `degraded`，不是内核的事。）

## 那这个原语还剩什么

只剩**一根引用**——`Task.executor_ref`。以及它带来的三条规则：

- **引用稳定，定义可编辑**（ADR-035）：换模型、改 prompt 不动历史 Task 的引用
- **内核从不解析它**："这个引用指向什么、现在能不能用"是网关的事
- **一个包可以有几条执行者**，所以引用写**全名**（`weather.collect`）——
  名字是身份，不是标签

这够不够撑一个文件？**够，但要说清它是四原语里最薄的一个。** 它答的是"**谁负责推**"——
这个问题的答案在内核里就是"一根指向谁的引用"，别的都在 `extensions/` 和网关那边。

← 来自 core/models.py 的 ExecutorConfigurationRef（`SetSubjectState` 已删）
"""

